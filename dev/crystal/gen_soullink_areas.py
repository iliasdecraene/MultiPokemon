"""Generate the Soul Link area table (crystal.AREAS / AREA_NAMES) from a pret/pokecrystal checkout.

Usage: python dev/crystal/gen_soullink_areas.py /path/to/pokecrystal > /tmp/areas.py
Then paste the output over the "# --- Soul Link areas (generated" block in client/yellowlink/crystal.py.

Source of truth:
  constants/map_constants.asm  -> map group/number (map id = group << 8 | number)
  data/maps/maps.asm           -> each map's environment + landmark (the Pokégear location name).
Rule: a map's area is its landmark (so every floor of a dungeon and every interior / gatehouse of a town or
route shares the area of the place it belongs to), with the overrides below for maps whose landmark is a
town but which are separate places (Team Rocket Base, Goldenrod Underground, the two ports) and the
LANDMARK_SPECIAL link rooms. dev/crystal/soullink_verify.py checks the table against the ROM's own map table
(group sizes, and that every area is exactly one ROM landmark).
"""
import os
import re
import sys

# map constant -> area key, for maps whose landmark isn't the right Nuzlocke area
OVERRIDES = {
    "TEAM_ROCKET_BASE_B1F": "team_rocket_base", "TEAM_ROCKET_BASE_B2F": "team_rocket_base",
    "TEAM_ROCKET_BASE_B3F": "team_rocket_base",
    "GOLDENROD_UNDERGROUND": "goldenrod_underground",
    "GOLDENROD_UNDERGROUND_SWITCH_ROOM_ENTRANCES": "goldenrod_underground",
    "GOLDENROD_UNDERGROUND_WAREHOUSE": "goldenrod_underground",
    "OLIVINE_PORT": "olivine_port", "OLIVINE_PORT_PASSAGE": "olivine_port",
    "VERMILION_PORT": "vermilion_port", "VERMILION_PORT_PASSAGE": "vermilion_port",
}
# landmark -> area key, where the plain lower-case landmark name isn't nice
KEY_FOR_LANDMARK = {
    "SILVER_CAVE": "mt_silver",
    "LIGHTHOUSE": "olivine_lighthouse",
    "LAV_RADIO_TOWER": "lavender_radio_tower",
}
NAMES = {
    "mt_silver": "Mt. Silver", "mt_mortar": "Mt. Mortar", "mt_moon": "Mt. Moon",
    "dragons_den": "Dragon's Den", "digletts_cave": "Diglett's Cave", "ruins_of_alph": "Ruins of Alph",
    "lake_of_rage": "Lake of Rage", "olivine_lighthouse": "Olivine Lighthouse",
    "radio_tower": "Radio Tower", "lavender_radio_tower": "Lavender Radio Tower",
    "pokecenter_2f": "Pokémon Center 2F", "time_capsule": "Time Capsule",
}


def parse(root):
    consts, g, n = [], 0, 0
    for line in open(os.path.join(root, "constants", "map_constants.asm")):
        s = line.split(";")[0].strip()
        if re.match(r"newgroup\s+\w+", s):
            g, n = g + 1, 0
            continue
        m = re.match(r"map_const\s+(\w+),", s)
        if m:
            n += 1
            consts.append((g, n, m.group(1)))
    maps, g = [], 0
    for line in open(os.path.join(root, "data", "maps", "maps.asm")):
        s = line.split(";")[0].strip()
        if re.match(r"MapGroup_\w+:", s):
            g, n = g + 1, 0
            continue
        m = re.match(r"map\s+(\w+),\s*(\w+),\s*(\w+),\s*(\w+)", s)
        if m and g:
            n += 1
            maps.append((g, n) + m.groups())
    assert len(consts) == len(maps), (len(consts), len(maps))
    out = []
    for (g1, n1, c), (g2, n2, _name, _ts, env, lm) in zip(consts, maps):
        assert (g1, n1) == (g2, n2), (c, g1, n1, g2, n2)
        out.append((g1, n1, c, env, lm[len("LANDMARK_"):]))
    return out


def area_key(const, landmark):
    if const in OVERRIDES:
        return OVERRIDES[const]
    if landmark == "SPECIAL":
        return const.lower()
    return KEY_FOR_LANDMARK.get(landmark, landmark.lower())


def area_name(key):
    if key in NAMES:
        return NAMES[key]
    return " ".join(w.capitalize() for w in key.split("_"))


def main():
    rows = parse(sys.argv[1])
    print("# --- Soul Link areas (generated by dev/crystal/gen_soullink_areas.py from pret/pokecrystal "
          "map_constants.asm + data/maps/maps.asm) ---")
    print("AREAS = {")
    for g, n, c, env, lm in rows:
        print("    0x%02X%02X: %r,  # %s (%s)" % (g, n, area_key(c, lm), c, env))
    print("}")
    keys = sorted(set(area_key(c, lm) for _, _, c, _, lm in rows))
    print("AREA_NAMES = {")
    for k in keys:
        print("    %r: %r," % (k, area_name(k)))
    print("}")
    print("# --- end of generated Soul Link areas ---")


if __name__ == "__main__":
    main()
